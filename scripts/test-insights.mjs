import assert from 'node:assert/strict';
import {extractRate,offersFor,lgDelta,rateChanges} from '../dist/insights.js';
const c=(id,title,status='captured')=>({id,title,status,url:'https://www.rakuten.com/shop/samsung',publisher:'Rakuten'});
assert.equal(extractRate(c('s','Samsung Up to 2% Cash Back')).isMaximum,true);
assert.equal(extractRate(c('s','Samsung 30% Off')),null);
assert.equal(extractRate(c('s','Samsung 2% Cash Back','challenge')),null);
assert.equal(extractRate({...c('s','Samsung 2% Cash Back'),url:'https://example.com'}),null);
const old={captures:[c('s','Samsung 2% Cash Back')],activities:[]};
const now={captures:[c('s','Samsung 5% Cash Back')],activities:[]};
assert.equal(rateChanges(now,old).length,1);
assert.equal(rateChanges({captures:[c('s','Samsung unavailable','error')],activities:[]},old).length,0);
assert.equal(rateChanges({captures:[c('s','Samsung Up to 5% Cash Back')],activities:[]},old).length,0);
assert.equal(rateChanges(now,null).length,0);
const offers=[{publisher:'Rakuten',brand:'LG',type:'cashback',storeClass:'public',isMaximum:false,rate:10}];
assert.equal(lgDelta({...offers[0],brand:'Samsung',rate:2},offers),'-8%p · 표시값 차이');
assert.equal(lgDelta({...offers[0],brand:'Samsung',isMaximum:true,rate:2},offers),'동일 기준 LG 없음');
assert.equal(lgDelta({...offers[0],brand:'Samsung',type:'reward',rate:2},offers),'동일 기준 LG 없음');
const verified={...now,activities:[{captureId:'s',brand:'Samsung',type:'cashback',rate:3,value:'3%',verified:true}]};
assert.equal(offersFor(verified).length,1);assert.equal(offersFor(verified)[0].rate,3);
console.log('Rate extraction, qualification, missing evidence and historical comparisons passed.');
